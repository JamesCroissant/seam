/**
 * Everything the plugin learns from the file system, as plain data.
 * The result is written to .seam/*.gen.ts so you can read exactly what the build decided.
 */
import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const SOURCE = /\.(tsx|ts|jsx|js)$/;

export const toPosix = (p: string) => p.split(sep).join("/");

// ---------- directives ----------

/** 'use client' / 'use server' at the very top of a file (comments allowed before it). */
export function readDirective(code: string): "use client" | "use server" | null {
  let s = code;
  for (;;) {
    s = s.trimStart();
    if (s.startsWith("//")) s = s.slice(s.indexOf("\n") + 1 || s.length);
    else if (s.startsWith("/*")) s = s.slice(s.indexOf("*/") + 2);
    else break;
  }
  const m = /^(['"])use (client|server)\1/.exec(s);
  return m ? (`use ${m[2]}` as "use client" | "use server") : null;
}

/** Stable across builds: same file + same export name → same id → same URL. */
export function actionId(relPath: string, exportName: string): string {
  return createHash("sha256").update(`${relPath}#${exportName}`).digest("hex").slice(0, 12);
}

async function walkFiles(dir: string): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const out: string[] = [];
  for (const e of entries) {
    if (e.name === "node_modules" || e.name.startsWith(".")) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walkFiles(p)));
    else if (SOURCE.test(e.name) && !e.name.endsWith(".d.ts")) out.push(p);
  }
  return out;
}

export interface DirectiveFiles {
  client: string[];
  server: string[];
}

export async function scanDirectives(root: string, appDir: string): Promise<DirectiveFiles> {
  const files = await walkFiles(join(root, appDir));
  const out: DirectiveFiles = { client: [], server: [] };
  for (const f of files.sort()) {
    const d = readDirective(await readFile(f, "utf8"));
    if (d === "use client") out.client.push(toPosix(relative(root, f)));
    if (d === "use server") out.server.push(toPosix(relative(root, f)));
  }
  return out;
}

// ---------- routes ----------

export interface RouteTreeNode {
  layout?: string;
  index?: string;
  static: Record<string, RouteTreeNode>;
  param?: { name: string; node: RouteTreeNode };
  rest?: { name: string; file: string };
}

const node = (): RouteTreeNode => ({ static: {} });
const PARAM = /^\[([A-Za-z_$][\w$]*)\]$/;
const REST = /^\[\.\.\.([A-Za-z_$][\w$]*)\]$/;

/**
 * File conventions (under app/routes):
 *   _layout.tsx        layout of this folder (wraps everything below)
 *   index.tsx          the folder's own page
 *   about.tsx          /about
 *   [id].tsx           /:id
 *   [...rest].tsx      /* (catch-all)
 *   folder/, [id]/     nested segments
 * Other files starting with "_" are ignored (helpers next to routes).
 */
export async function scanRoutes(root: string, routesDir: string): Promise<RouteTreeNode> {
  const top = node();
  await fill(top, join(root, routesDir), root);
  return top;
}

async function fill(target: RouteTreeNode, dir: string, root: string): Promise<void> {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const full = join(dir, e.name);
    const rel = toPosix(relative(root, full));
    if (e.isDirectory()) {
      if (e.name.startsWith(".") || e.name === "node_modules") continue;
      await fill(childFor(target, e.name, rel), full, root);
      continue;
    }
    if (!SOURCE.test(e.name) || e.name.endsWith(".d.ts")) continue;
    const base = e.name.replace(SOURCE, "");
    if (base === "_layout") target.layout = rel;
    else if (base === "index") target.index = rel;
    else if (base.startsWith("_")) continue;
    else if (REST.test(base)) target.rest = { name: REST.exec(base)![1], file: rel };
    else childFor(target, base, rel).index = rel;
  }
}

function childFor(target: RouteTreeNode, name: string, where: string): RouteTreeNode {
  const p = PARAM.exec(name);
  if (p) {
    if (target.param && target.param.name !== p[1]) {
      throw new Error(`[seam] Two different params at the same level: [${target.param.name}] and [${p[1]}] (${where})`);
    }
    target.param ??= { name: p[1], node: node() };
    return target.param.node;
  }
  if (REST.test(name)) throw new Error(`[seam] A catch-all must be a file, not a folder: ${where}`);
  return (target.static[name] ??= node());
}

// ---------- code generation ----------

const HEADER = "// Generated by Seam. Do not edit. This file shows what the build decided.\n";

function importPath(fromDir: string, root: string, rel: string): string {
  const p = toPosix(relative(fromDir, join(root, rel)));
  return p.startsWith(".") ? p : `./${p}`;
}

export function generateRoutes(tree: RouteTreeNode, genDir: string, root: string, name: "routes" | "views" = "routes"): string {
  const entry = (rel: string) => `{ file: ${JSON.stringify(rel)}, load: () => import(${JSON.stringify(importPath(genDir, root, rel))}) }`;
  const emit = (n: RouteTreeNode, indent: string): string => {
    const lines: string[] = [];
    const inner = indent + "  ";
    if (n.layout) lines.push(`${inner}layout: ${entry(n.layout)},`);
    if (n.index) lines.push(`${inner}index: ${entry(n.index)},`);
    const statics = Object.entries(n.static);
    if (statics.length) {
      lines.push(`${inner}static: {`);
      for (const [k, v] of statics) lines.push(`${inner}  ${JSON.stringify(k)}: ${emit(v, inner + "  ")},`);
      lines.push(`${inner}},`);
    }
    if (n.param) lines.push(`${inner}param: { name: ${JSON.stringify(n.param.name)}, node: ${emit(n.param.node, inner)} },`);
    if (n.rest) lines.push(`${inner}rest: { name: ${JSON.stringify(n.rest.name)}, entry: ${entry(n.rest.file)} },`);
    return lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "{}";
  };
  const note = name === "views" ? "// Served under /_v/. " : "// ";
  return `${HEADER}import type { RouteNode } from "seam";\n\n${note}Match order at each level: static > [param] > [...rest]\nexport const ${name}: RouteNode = ${emit(tree, "")};\n`;
}

export interface ActionExport {
  id: string;
  file: string;
  name: string;
}

export function generateActions(list: ActionExport[], genDir: string, root: string): string {
  const lines = list.map(
    (a) =>
      `  // ${a.file} → ${a.name}  (POST /_action/${a.id})\n  ${JSON.stringify(a.id)}: () => import(${JSON.stringify(importPath(genDir, root, a.file))}).then((m) => m.${a.name}),`,
  );
  return `${HEADER}import type { ActionMap } from "seam";\n\nexport const actions: ActionMap = {\n${lines.join("\n")}\n};\n`;
}

export function generateIslands(files: string[], genDir: string, root: string): string {
  const lines = files.map((f) => `  ${JSON.stringify(f)}: () => import(${JSON.stringify(importPath(genDir, root, f))}),`);
  return `${HEADER}// Only these files are sent to the browser (plus the navigation script).\nexport const islands: Record<string, () => Promise<Record<string, unknown>>> = {\n${lines.join("\n")}\n};\n`;
}

// ---------- typed API (*.api.ts) ----------

export const API_FILE = /\.api\.[cm]?[jt]sx?$/;

export interface ApiExport {
  file: string;
  name: string;
  path: string;
}

/**
 * Every value export of a *.api.ts file must be `export const name = get("/api/...", {...})`
 * with a string literal path: the build reads the URL from the source, never by running it.
 * `js` is the file after TypeScript was stripped.
 */
export function extractApiExports(js: string, file: string, exportNames: string[]): ApiExport[] {
  const found = new Map<string, string>();
  const re = /export\s+const\s+([A-Za-z_$][\w$]*)\s*=\s*get\s*\(\s*(["'])([^"'`]+)\2/g;
  for (const m of js.matchAll(re)) found.set(m[1], m[3]);

  return exportNames.map((name) => {
    const path = found.get(name);
    if (!path) {
      throw new Error(`[seam] ${file}: export "${name}" must be \`export const ${name} = get("/api/...", { ... })\` with a string literal path.`);
    }
    if (!path.startsWith("/api/")) throw new Error(`[seam] ${file}: "${path}" must start with /api/`);
    return { file, name, path };
  });
}

/** Two endpoints with the same shape (e.g. /api/a/:id and /api/a/:slug) would be ambiguous. */
export function checkApiConflicts(list: ApiExport[]): void {
  const seen = new Map<string, ApiExport>();
  for (const a of list) {
    const shape = a.path.replace(/:[^/]+/g, ":").replace(/\*[^/]+/g, "*");
    const prev = seen.get(shape);
    if (prev) throw new Error(`[seam] ${a.path} (${a.file} → ${a.name}) conflicts with ${prev.path} (${prev.file} → ${prev.name})`);
    seen.set(shape, a);
  }
}

export function generateApi(list: ApiExport[], genDir: string, root: string): string {
  const lines = list.map(
    (a) =>
      `  // ${a.file} → ${a.name}\n  { method: "GET", path: ${JSON.stringify(a.path)}, load: () => import(${JSON.stringify(importPath(genDir, root, a.file))}).then((m) => m.${a.name}) },`,
  );
  return `${HEADER}import type { ApiEntry } from "seam";\n\n// Typed GET endpoints. In the browser each export is just fetch(path).\nexport const api: ApiEntry[] = [\n${lines.join("\n")}\n];\n`;
}

export async function scanApiFiles(root: string, appDir: string): Promise<string[]> {
  return (await walkFiles(join(root, appDir)))
    .filter((f) => API_FILE.test(f))
    .map((f) => toPosix(relative(root, f)))
    .sort();
}
